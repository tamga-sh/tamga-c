static const char *PROOF_ACCOUNT_ID = "00000000-0000-0000-0000-000000000000";
static const char *PROOF_MACHINE_ID = "00000000-0000-0000-0000-000000000001";
static const char *PROOF_FINGERPRINT = "fp-abc";
static const char *PROOF_DATASET = "{\"cores\":4}";

int main(void) {
    bool valid = false;
    TamgaErrorCode code =
        tamga_offline_proof_verify(PROOF_STR, PROOF_PUBKEY, sizeof(PROOF_PUBKEY), PROOF_ACCOUNT_ID,
                                   PROOF_MACHINE_ID, PROOF_FINGERPRINT, PROOF_DATASET, &valid);
    if (code != TAMGA_OK) {
        const char *err = tamga_last_error_message();
        fprintf(stderr, "test_offline_proof: verify call failed, code=%d, err=%s\n", (int)code,
                err ? err : "(none)");
        return 1;
    }
    if (!valid) {
        fprintf(stderr, "test_offline_proof: known-good fixture reported invalid\n");
        return 1;
    }

    /* Tampered dataset must fail verification (call still succeeds, proof
     * is just invalid) -- regression case for the field-order gotcha. */
    bool tampered_valid = true;
    code = tamga_offline_proof_verify(PROOF_STR, PROOF_PUBKEY, sizeof(PROOF_PUBKEY),
                                      PROOF_ACCOUNT_ID, PROOF_MACHINE_ID, PROOF_FINGERPRINT,
                                      "{\"cores\":999}", &tampered_valid);
    if (code != TAMGA_OK || tampered_valid) {
        fprintf(stderr, "test_offline_proof: tampered dataset not rejected as expected\n");
        return 1;
    }

    /* _generate is a documented non-implementation, not a crash. */
    char *generated = NULL;
    code = tamga_offline_proof_generate(PROOF_ACCOUNT_ID, PROOF_ACCOUNT_ID, PROOF_MACHINE_ID,
                                        PROOF_FINGERPRINT, PROOF_DATASET, &generated);
    if (code != TAMGA_ERR_UNKNOWN || generated != NULL) {
        fprintf(stderr, "test_offline_proof: _generate did not report its documented "
                        "non-implementation as expected\n");
        return 1;
    }

    printf("test_offline_proof: OK\n");
    return 0;
}
